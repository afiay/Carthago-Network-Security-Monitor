        public static IReadOnlyList<IDetectionRule> CreateAvailableRules()
        {
            var core = CreateDefaultRules();
            var packRules = new CompiledContentPackRegistry()
                .GetAllRuleRegistrations()
                .Select(static registration => registration.CompiledRule)
                .Where(static rule => rule != null)
                .Cast<IDetectionRule>();

            return core.Concat(packRules)
                .OrderBy(static rule => rule.Descriptor.RuleId, System.StringComparer.OrdinalIgnoreCase)
                .ToArray();
        }
