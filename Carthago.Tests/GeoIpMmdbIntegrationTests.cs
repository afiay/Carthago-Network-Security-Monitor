            using var geo = new GeoIpService(root);
            Assert.Equal(GeoIpService.DatabaseAvailability.Ready, geo.CityDatabaseStatus);
            Assert.Equal(GeoIpService.DatabaseAvailability.Unavailable, geo.AsnDatabaseStatus);
            var found = geo.LookupWithOutcomes("::ffff:81.2.69.142");
            Assert.Equal(GeoIpService.LookupOutcome.Found, found.City);
            Assert.Equal(GeoIpService.LookupOutcome.NotAttempted, found.Asn);
            Assert.Equal("GB", found.Info?.CountryIso2);
            var absent = geo.LookupWithOutcomes("8.8.8.8");
            Assert.Equal(GeoIpService.LookupOutcome.NotFound, absent.City);
            Assert.Null(absent.Info);
            Assert.Null(geo.Lookup("192.168.1.1"));
            Assert.Equal(new GeoIpService.LookupHealthSnapshot(1, 1, 0), geo.CityLookupHealth);
            Assert.Equal(0L, geo.AsnLookupHealth.Attempts);
            geo.Dispose();
            Assert.False(geo.IsCityDbAvailable);
            Assert.Equal(GeoIpService.LookupOutcome.NotAttempted, geo.LookupWithOutcomes("81.2.69.142").City);
            Assert.Equal(2L, geo.CityLookupHealth.Attempts);
        }
        finally { Directory.Delete(root, true); }
    }
