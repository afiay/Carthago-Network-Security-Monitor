    [Fact]
    public void Real_Readers_Preserve_Independent_Partial_Results()
    {
        var root = Path.Combine(Path.GetTempPath(), "carthago-mmdb-" + Guid.NewGuid().ToString("N"));
        try
        {
            var data = Directory.CreateDirectory(Path.Combine(root, "Data"));
            File.WriteAllBytes(Path.Combine(data.FullName, "GeoLite2-City.mmdb"), Convert.FromBase64String(CityFixture));
            File.WriteAllBytes(Path.Combine(data.FullName, "GeoLite2-ASN.mmdb"), Convert.FromBase64String(AsnFixture));
            using var geo = new GeoIpService(root);
            Assert.True(geo.IsCityDbAvailable);
            Assert.True(geo.IsAsnDbAvailable);

            var asn = geo.LookupWithOutcomes("1.0.0.1");
            Assert.Equal(GeoIpService.LookupOutcome.NotFound, asn.City);
            Assert.Equal(GeoIpService.LookupOutcome.Found, asn.Asn);
            Assert.NotNull(asn.Info);
            Assert.Equal(15169L, asn.Info!.Asn);
            Assert.Equal("Google Inc.", asn.Info.AsnOrganization);
            Assert.Null(asn.Info.CountryIso2);
            Assert.Null(asn.Info.Latitude);

            var city = geo.LookupWithOutcomes("81.2.69.142");
            Assert.Equal(GeoIpService.LookupOutcome.Found, city.City);
            Assert.Equal(GeoIpService.LookupOutcome.NotFound, city.Asn);
            Assert.Equal("GB", city.Info?.CountryIso2);
            Assert.Null(city.Info!.Asn);

            var absent = geo.LookupWithOutcomes("8.8.8.8");
            Assert.Equal(GeoIpService.LookupOutcome.NotFound, absent.City);
            Assert.Equal(GeoIpService.LookupOutcome.NotFound, absent.Asn);
            Assert.Null(absent.Info);
            Assert.Equal(new GeoIpService.LookupHealthSnapshot(1, 2, 0), geo.CityLookupHealth);
            Assert.Equal(new GeoIpService.LookupHealthSnapshot(1, 2, 0), geo.AsnLookupHealth);
        }
        finally { Directory.Delete(root, true); }
    }

    [Fact]
    public void Real_Readers_Cache_Normalized_Hits_And_Misses_With_Bounded_Lifetime()
    {
        var root = Path.Combine(Path.GetTempPath(), "carthago-mmdb-" + Guid.NewGuid().ToString("N"));
        try
        {
            var data = Directory.CreateDirectory(Path.Combine(root, "Data"));
            File.WriteAllBytes(Path.Combine(data.FullName, "GeoLite2-City.mmdb"), Convert.FromBase64String(CityFixture));
            long now = 0;
            using var geo = new GeoIpService(root, cacheCapacity: 2, clock: () => now);
            Assert.Equal("GB", geo.Lookup("81.2.69.142")?.CountryIso2);
            Assert.Equal("GB", geo.Lookup("::ffff:81.2.69.142")?.CountryIso2);
            Assert.Null(geo.Lookup("8.8.8.8"));
            Assert.Null(geo.Lookup("8.8.8.8"));
            Assert.Equal(2L, geo.CityLookupHealth.Attempts);
            now = 300_000;
            Assert.Equal("GB", geo.Lookup("81.2.69.142")?.CountryIso2);
            Assert.Equal(3L, geo.CityLookupHealth.Attempts);
            Assert.Null(geo.Lookup("1.0.0.1"));
            Assert.Equal("GB", geo.Lookup("81.2.69.142")?.CountryIso2);
            Assert.Equal(5L, geo.CityLookupHealth.Attempts);
            geo.Dispose();
            Assert.Null(geo.Lookup("81.2.69.142"));
            Assert.Equal(5L, geo.CityLookupHealth.Attempts);
        }
        finally { Directory.Delete(root, true); }
    }
